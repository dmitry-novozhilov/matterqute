// gen строит internal/emoji/groups_gen.go — группы и порядок эмодзи для окна
// выбора — из Unicode emoji-test.txt (https://unicode.org/Public/emoji/15.1/emoji-test.txt):
//
//	go run ./internal/emoji/gen -in emoji-test.txt -out internal/emoji/groups_gen.go
//
// Берём полностью квалифицированные эмодзи в порядке CLDR, без группы
// Component и без вариантов цвета кожи; коды — как в model.SystemEmojis
// (строчный hex через «-»), с селекторами fe0f; сопоставляем без них.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"log"
	"os"
	"strings"
)

func main() {
	in := flag.String("in", "emoji-test.txt", "Unicode emoji-test.txt")
	out := flag.String("out", "groups_gen.go", "generated Go file")
	flag.Parse()
	f, err := os.Open(*in)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	type group struct {
		name  string
		codes []string
	}
	var groups []*group
	version := ""
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if v, ok := strings.CutPrefix(line, "# Version: "); ok {
			version = v
		}
		if name, ok := strings.CutPrefix(line, "# group: "); ok {
			groups = append(groups, &group{name: name})
			continue
		}
		seq, rest, ok := strings.Cut(line, ";")
		if !ok || strings.HasPrefix(line, "#") || !strings.HasPrefix(strings.TrimSpace(rest), "fully-qualified") || len(groups) == 0 {
			continue
		}
		g := groups[len(groups)-1]
		if g.name == "Component" {
			continue
		}
		var parts []string
		tone := false
		for _, cp := range strings.Fields(seq) {
			cp = strings.ToLower(cp)
			if cp >= "1f3fb" && cp <= "1f3ff" && len(cp) == 5 {
				tone = true
			}
			parts = append(parts, cp)
		}
		if !tone {
			g.codes = append(g.codes, strings.Join(parts, "-"))
		}
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by go run ./internal/emoji/gen from Unicode emoji-test.txt %s; DO NOT EDIT.\n"+
		"// The data comes from Unicode, Inc. under the Unicode License V3: see LICENSE-unicode.txt.\n\npackage emoji\n\n", version)
	b.WriteString("var unicodeGroups = []unicodeGroup{\n")
	for _, g := range groups {
		if g.name == "Component" {
			continue
		}
		fmt.Fprintf(&b, "\t{%q, []string{", g.name)
		for i, c := range g.codes {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", c)
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n")
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
}
